"""platforms.md generator: one table per probe, one row per run, deterministic order, the
generated-by header, and honest oracle verdicts from the manifest."""

import json
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

from report.platforms import generate, render_markdown, run_rows, vendor_of  # noqa: E402


def make_run(root: Path, name: str, probe: str, backend: str, label: str,
             status: str = "ok",
             device: str = "AMD Radeon RX 9070 XT (RADV GFX1201)", driver: str = "26.2.4",
             date: str = "2026-01-01T00:00:00Z", value: float = 634.3):
    d = root / name
    d.mkdir(parents=True, exist_ok=True)
    (d / "manifest.json").write_text(json.dumps({
        "v": 1, "run_id": d.name, "probe": probe, "backend": backend, "label": label,
        "status": status, "started_utc": date,
        "steps": [{"name": probe, "status": status, "returncode": 0, "failed_checks": 0}],
    }))
    records = [
        {"v": 1, "t_ns": 1, "src": "probe", "probe": probe, "backend": backend,
         "type": "probe_start", "params": {}},
        {"v": 1, "t_ns": 2, "src": "probe", "probe": probe, "backend": backend,
         "type": "declared", "key": "device.name", "value": device, "source": "fake"},
        {"v": 1, "t_ns": 3, "src": "probe", "probe": probe, "backend": backend,
         "type": "declared", "key": "vulkan.driver_version", "value": driver,
         "source": "vkGetPhysicalDeviceProperties"},
        {"v": 1, "t_ns": 4, "src": "probe", "probe": probe, "backend": backend,
         "type": "measure", "name": "gpu_read", "value": value, "unit": "GB/s",
         "tags": {"source": "vulkan_device_local", "per_rep": {"min": value, "max": value}},
         "verified": True},
        {"v": 1, "t_ns": 5, "src": "probe", "probe": probe, "backend": backend,
         "type": "probe_end", "status": status, "failed_checks": 0},
    ]
    (d / "probe.jsonl").write_text("".join(json.dumps(r) + "\n" for r in records))
    (d / "env.json").write_text(json.dumps({"v": 1, "amd": {"cards": [{"driver": "amdgpu"}]}}))
    return d


class PlatformsTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.runs = self.root / "runs"

    def tearDown(self):
        self.tmp.cleanup()

    def test_one_table_per_probe_one_row_per_run(self):
        make_run(self.runs, "20260101T000000Z-memory-vulkan-idle", "memory", "vulkan", "idle")
        make_run(self.runs, "20260102T000000Z-memory-vulkan-cpu50", "memory", "vulkan", "cpu50")
        make_run(self.runs, "20260103T000000Z-mma-vulkan-idle", "mma", "vulkan", "idle")
        out = self.root / "out" / "platforms.md"
        n = generate(self.runs, out)
        self.assertEqual(n, 3)
        text = out.read_text()
        self.assertIn("Generated by `./echolock platforms`", text)
        self.assertIn("## memory", text)
        self.assertIn("## mma", text)
        self.assertIn("20260101T000000Z-memory-vulkan-idle", text)
        # the memory headline: device-local gpu_read
        self.assertIn("| 634.3 GB/s |", text)
        # the mma run has no mma.tflops.fp16 in its records: the cell says so, not a guess
        mma_row = [l for l in text.splitlines() if "20260103" in l][0]
        self.assertIn("| — |", mma_row)

    def test_deterministic_output(self):
        make_run(self.runs, "20260101T000000Z-memory-vulkan-a", "memory", "vulkan", "a")
        make_run(self.runs, "20260102T000000Z-memory-vulkan-b", "memory", "vulkan", "b",
                 value=500.0)
        o1, o2 = self.root / "p1.md", self.root / "p2.md"
        generate(self.runs, o1)
        generate(self.runs, o2)
        self.assertEqual(o1.read_text(), o2.read_text())
        text = o1.read_text()
        # rows sorted: run 20260101 before 20260102
        self.assertLess(text.index("20260101T000000Z-memory-vulkan-a"),
                        text.index("20260102T000000Z-memory-vulkan-b"))

    def test_oracle_verdict_from_manifest(self):
        make_run(self.runs, "20260101T000000Z-memory-vulkan-ok", "memory", "vulkan", "ok", "ok")
        make_run(self.runs, "20260102T000000Z-memory-vulkan-bad", "memory", "vulkan", "bad",
                 "verify_failed")
        rows = {r["run_id"]: r for r in run_rows(self.runs)}
        self.assertEqual(rows["20260101T000000Z-memory-vulkan-ok"]["oracle"], "pass")
        self.assertEqual(rows["20260102T000000Z-memory-vulkan-bad"]["oracle"], "verify failed")

    def test_vendor_parsing(self):
        self.assertEqual(vendor_of("AMD Radeon RX 9070 XT (RADV GFX1201)", {}), "AMD")
        self.assertEqual(vendor_of("NVIDIA GeForce RTX 5090", {}), "NVIDIA")
        self.assertEqual(vendor_of(None, {"amd": {"cards": [{}]}}), "AMD")
        self.assertEqual(vendor_of(None, {"nvidia": {"nvml": {"devices": [{}]}}}), "NVIDIA")
        self.assertEqual(vendor_of("Mystery Corp Card", {}), "?")

    def test_render_markdown_header_and_columns(self):
        make_run(self.runs, "20260101T000000Z-memory-vulkan-idle", "memory", "vulkan", "idle")
        text = render_markdown(run_rows(self.runs))
        self.assertIn("# Platforms", text)
        self.assertIn("Generated by `./echolock platforms`", text)
        self.assertIn("| device | vendor | backend | driver | label |", text)


if __name__ == "__main__":
    unittest.main()
